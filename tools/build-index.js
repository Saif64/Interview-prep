#!/usr/bin/env node
/**
 * Regenerates the two index files from the repository contents:
 *
 *   SOLUTIONS.md            every solution in the repo, grouped by LeetCode problem
 *   neetcode-150/README.md  the NeetCode 150 checklist with progress
 *
 * Both are generated — edit this script, not the Markdown.
 * Run: npm run index   (or: node tools/build-index.js)
 *
 * Problem metadata comes from tools/leetcode-meta.json, a cached snapshot of LeetCode's
 * public problem list, so this works offline and in CI. Refresh it with:
 *   node tools/refresh-leetcode-meta.js
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const META = JSON.parse(fs.readFileSync(path.join(__dirname, 'leetcode-meta.json'), 'utf8'));
const NEETCODE = JSON.parse(fs.readFileSync(path.join(__dirname, 'neetcode-150.json'), 'utf8'));

const SKIP_DIRS = new Set(['.git', 'node_modules', '.github', 'tools']);
const LANGUAGE_BY_EXT = { '.js': 'JavaScript', '.cpp': 'C++', '.java': 'Java' };
const DIFFICULTY_BADGE = { Easy: '🟩 Easy', Medium: '🟨 Medium', Hard: '🟥 Hard' };

// ---------------------------------------------------------------------------
// Scanning
// ---------------------------------------------------------------------------

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (SKIP_DIRS.has(entry.name)) return [];
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return LANGUAGE_BY_EXT[path.extname(entry.name)] ? [full] : [];
  });

/** Pull a LeetCode slug out of a file: from a URL in the header, or from its own name. */
const slugFor = (file) => {
  const header = fs.readFileSync(file, 'utf8').slice(0, 2000);

  const url = header.match(/leetcode\.com\/problems\/([a-z0-9-]+)/i);
  if (url && META[url[1]]) return url[1];

  const base = path.basename(file, path.extname(file));

  // "0217-contains-duplicate" or "contains-duplicate"
  const named = base.replace(/^\d+[-_]?/, '');
  if (META[named]) return named;

  // "leetcode217" / "leetcode_217" -> look the number up
  const numbered = base.match(/^leetcode[-_ ]?(\d+)$/i);
  if (numbered) {
    const id = Number(numbered[1]);
    const found = Object.keys(META).find((slug) => META[slug][0] === id);
    if (found) return found;
  }
  return null;
};

const mdEscape = (text) => text.replace(/\|/g, '\\|');
const linkTo = (file) => encodeURI(path.relative(ROOT, file).split(path.sep).join('/'));

// ---------------------------------------------------------------------------
// SOLUTIONS.md — every solved problem, every language
// ---------------------------------------------------------------------------

const buildSolutionsIndex = (files) => {
  const problems = new Map(); // slug -> { id, title, difficulty, files: [] }
  const concepts = new Map(); // directory -> [files]

  for (const file of files) {
    const slug = slugFor(file);
    if (slug) {
      const [id, title, difficulty] = META[slug];
      if (!problems.has(slug)) problems.set(slug, { id, title, difficulty, slug, files: [] });
      problems.get(slug).files.push(file);
    } else {
      const dir = path.dirname(path.relative(ROOT, file));
      if (!concepts.has(dir)) concepts.set(dir, []);
      concepts.get(dir).push(file);
    }
  }

  const solved = [...problems.values()].sort((a, b) => a.id - b.id);
  const byDifficulty = (level) => solved.filter((p) => p.difficulty === level).length;

  const lines = [
    '# Solution Index',
    '',
    '<!-- Generated by tools/build-index.js — do not edit by hand. Run: npm run index -->',
    '',
    `**${solved.length} LeetCode problems solved** across ${files.length} files.`,
    '',
    `| 🟩 Easy | 🟨 Medium | 🟥 Hard | Total |`,
    `| :-----: | :-------: | :-----: | :---: |`,
    `| ${byDifficulty('Easy')} | ${byDifficulty('Medium')} | ${byDifficulty('Hard')} | ${solved.length} |`,
    '',
    'Looking for a structured path instead of a flat list? Start with the',
    '[NeetCode 150](neetcode-150/README.md).',
    '',
    '## Problems',
    '',
    '| # | Problem | Difficulty | Solutions |',
    '| --: | :--- | :--- | :--- |',
  ];

  for (const problem of solved) {
    const links = problem.files
      .map((file) => `[${LANGUAGE_BY_EXT[path.extname(file)]}](${linkTo(file)})`)
      .join(' · ');
    lines.push(
      `| ${problem.id} | [${mdEscape(problem.title)}](https://leetcode.com/problems/${problem.slug}/) ` +
        `| ${DIFFICULTY_BADGE[problem.difficulty] ?? problem.difficulty} | ${links} |`
    );
  }

  lines.push('', '## Data structures & algorithms from scratch', '');
  lines.push('Implementations and exercises that are not tied to a specific LeetCode problem.', '');

  for (const dir of [...concepts.keys()].sort()) {
    const items = concepts
      .get(dir)
      .sort()
      .map((file) => `[${path.basename(file)}](${linkTo(file)})`)
      .join(' · ');
    lines.push(`- **${dir}** — ${items}`);
  }

  lines.push('');
  return { markdown: lines.join('\n'), solvedSlugs: new Set(problems.keys()), solved };
};

// ---------------------------------------------------------------------------
// neetcode-150/README.md — the checklist
// ---------------------------------------------------------------------------

const buildNeetcodeIndex = () => {
  const byPattern = new Map();
  for (const problem of NEETCODE) {
    if (!byPattern.has(problem.pattern)) byPattern.set(problem.pattern, []);
    byPattern.get(problem.pattern).push(problem);
  }

  let done = 0;
  for (const problem of NEETCODE) {
    if (fs.existsSync(path.join(ROOT, 'neetcode-150', problem.dir, problem.file))) done++;
  }
  const percent = Math.round((done / NEETCODE.length) * 100);
  const filled = Math.round(percent / 5);

  const lines = [
    '# NeetCode 150',
    '',
    '<!-- Generated by tools/build-index.js — do not edit by hand. Run: npm run index -->',
    '',
    'The 150 problems from [neetcode.io](https://neetcode.io/practice), grouped by pattern.',
    'Every solution here is JavaScript, commented with the idea behind it, and **runnable**:',
    '',
    '```bash',
    'node neetcode-150/01-arrays-and-hashing/0001-two-sum.js   # runs its own assertions',
    'node tools/test.js                                        # runs all of them',
    '```',
    '',
    `**Progress: ${done}/${NEETCODE.length} (${percent}%)**`,
    '',
    `\`${'█'.repeat(filled)}${'░'.repeat(20 - filled)}\``,
    '',
    '⭐ marks the 75 problems that are also on **Blind 75** — the shortlist to do first if',
    'you are short on time.',
    '',
    '## Contents',
    '',
  ];

  for (const [pattern, problems] of byPattern) {
    const anchor = pattern.toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/ +/g, '-');
    lines.push(`- [${pattern}](#${anchor}) — ${problems.length} problems`);
  }
  lines.push('');

  for (const [pattern, problems] of byPattern) {
    lines.push(`## ${pattern}`, '');
    lines.push('| ✔ | # | Problem | Difficulty | Solution |');
    lines.push('| :-: | --: | :--- | :--- | :--- |');
    for (const problem of problems) {
      const relative = `${problem.dir}/${problem.file}`;
      const exists = fs.existsSync(path.join(ROOT, 'neetcode-150', relative));
      const star = problem.blind75 ? ' ⭐' : '';
      lines.push(
        `| ${exists ? '✅' : '⬜'} | ${problem.id} ` +
          `| [${mdEscape(problem.title)}](https://leetcode.com/problems/${problem.slug}/)${star} ` +
          `| ${DIFFICULTY_BADGE[problem.difficulty]} ` +
          `| ${exists ? `[JavaScript](${encodeURI(relative)})` : '—'} |`
      );
    }
    lines.push('');
  }

  lines.push(
    '---',
    '',
    'Problem list from [neetcode-gh/leetcode](https://github.com/neetcode-gh/leetcode).',
    'Solutions and explanations in this folder are original.',
    ''
  );
  return { markdown: lines.join('\n'), done, total: NEETCODE.length };
};

// ---------------------------------------------------------------------------

const files = walk(ROOT);
const solutions = buildSolutionsIndex(files);
const neetcode = buildNeetcodeIndex();

fs.writeFileSync(path.join(ROOT, 'SOLUTIONS.md'), solutions.markdown);
fs.writeFileSync(path.join(ROOT, 'neetcode-150', 'README.md'), neetcode.markdown);

console.log(`SOLUTIONS.md           ${solutions.solved.length} problems, ${files.length} files`);
console.log(`neetcode-150/README.md ${neetcode.done}/${neetcode.total} complete`);
